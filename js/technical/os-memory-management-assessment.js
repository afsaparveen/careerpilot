function showError(message) {
  errorBox.textContent = message;
  errorBox.hidden = false;
}


function hideError() {
  errorBox.hidden = true;
  errorBox.textContent = "";
}


function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}


function renderQuestions() {
  questionsContainer.innerHTML = "";

  questions.forEach((item, index) => {
    const questionWrapper = document.createElement("div");
    questionWrapper.className = "question";

    questionWrapper.innerHTML = `
      <div class="question-header">
        <span class="question-number">
          Question ${index + 1}
        </span>
      </div>

      <h3>
        ${escapeHtml(item.question)}
      </h3>

      <div class="options">
        ${item.options
          .map(
            (option, optionIndex) => `
              <label class="option">
                <input
                  type="radio"
                  name="question-${index}"
                  value="${optionIndex}"
                />
                <span>
                  ${String.fromCharCode(65 + optionIndex)}.
                  ${escapeHtml(option)}
                </span>
              </label>
            `
          )
          .join("")}
      </div>
    `;

    questionsContainer.appendChild(questionWrapper);
  });

  updateProgress();
}


function getAnsweredCount() {
  let answered = 0;

  questions.forEach((_, index) => {
    const selected = document.querySelector(
      `input[name="question-${index}"]:checked`
    );

    if (selected) {
      answered++;
    }
  });

  return answered;
}


function updateProgress() {
  const answered = getAnsweredCount();

  answeredText.textContent =
    `${answered} answered`;

  if (answered === questions.length) {
    progressText.textContent =
      `All ${questions.length} questions answered`;
  } else {
    const nextNumber = Math.min(answered + 1, questions.length);

    progressText.textContent =
      `Question ${nextNumber} of ${questions.length}`;
  }

  const percentage =
    (answered / questions.length) * 100;

  progressBar.style.width =
    `${Math.max(5, percentage)}%`;
}


function validateAllAnswered() {
  const unanswered = [];

  questions.forEach((_, index) => {
    const selected = document.querySelector(
      `input[name="question-${index}"]:checked`
    );

    if (!selected) {
      unanswered.push(index + 1);
    }
  });

  if (unanswered.length > 0) {
    showError(
      `Please answer all questions before submitting. Unanswered question(s): ${unanswered.join(", ")}.`
    );

    const firstUnanswered = unanswered[0] - 1;

    const target =
      document.querySelectorAll(".question")[firstUnanswered];

    if (target) {
      target.scrollIntoView({
        behavior: "smooth",
        block: "center"
      });
    }

    return false;
  }

  hideError();
  return true;
}


async function saveAssessmentResult(score, percentage, passed) {
  if (!currentUser) {
    throw new Error("User is not authenticated.");
  }

  const userRef = doc(
    db,
    "users",
    currentUser.uid
  );

  const snapshot = await getDoc(userRef);

  const existingData =
    snapshot.exists()
      ? snapshot.data()
      : {};

  const existingProgress =
    existingData.osProgress || {};

  const existingAssessments =
    existingProgress.assessments || {};

  const existingCompletedChapters =
    existingProgress.completedChapters || {};

  const assessmentHistory =
    existingAssessments[ASSESSMENT_KEY]?.attempts || [];

  const attempt = {
    score,
    total: questions.length,
    percentage,
    passed,
    completedAt: new Date().toISOString()
  };

  const updatedProgress = {
    ...existingProgress,

    assessments: {
      ...existingAssessments,

      [ASSESSMENT_KEY]: {
        score,
        total: questions.length,
        percentage,
        passed,
        attempts: [
          ...assessmentHistory,
          attempt
        ]
      }
    },

    completedChapters: {
      ...existingCompletedChapters,

      [CHAPTER_ID]: passed
        ? true
        : Boolean(existingCompletedChapters[CHAPTER_ID])
    }
  };

  await setDoc(
    userRef,
    {
      osProgress: updatedProgress
    },
    {
      merge: true
    }
  );

  progressData = updatedProgress;
}


async function submitAssessment() {
  if (submitted) {
    return;
  }

  if (!validateAllAnswered()) {
    return;
  }

  submitBtn.disabled = true;
  submitBtn.textContent = "Checking...";

  let score = 0;

  questions.forEach((question, index) => {
    const selected = document.querySelector(
      `input[name="question-${index}"]:checked`
    );

    if (
      selected &&
      Number(selected.value) === question.answer
    ) {
      score++;
    }
  });

  const percentage =
    Math.round(
      (score / questions.length) * 100
    );

  const passed =
    percentage >= PASS_PERCENTAGE;

  try {
    await saveAssessmentResult(
      score,
      percentage,
      passed
    );

    submitted = true;

    showResult(
      score,
      percentage,
      passed
    );

  } catch (error) {
    console.error(error);

    showError(
      "Your result could not be saved. Please check your Firebase connection and try again."
    );

    submitBtn.disabled = false;
    submitBtn.textContent = "Submit Assessment";
  }
}


function showResult(score, percentage, passed) {
  resultBox.hidden = false;

  scoreValue.textContent =
    `${score}/${questions.length}`;

  percentageValue.textContent =
    `${percentage}%`;

  passValue.textContent =
    `${PASS_SCORE}/${questions.length}`;

  if (passed) {
    resultIcon.textContent = "✓";
    resultTitle.textContent =
      "Chapter 7 Passed!";

    resultMessage.textContent =
      `Great work! You scored ${score}/${questions.length} (${percentage}%). Memory Management is now completed, and the next OS chapter is unlocked.`;

  } else {
    resultIcon.textContent = "!";
    resultTitle.textContent =
      "Assessment Not Passed";

    resultMessage.textContent =
      `You scored ${score}/${questions.length} (${percentage}%). You need at least ${PASS_SCORE}/${questions.length} (75%) to pass this chapter. Review Memory Management and try again.`;
  }

  form.style.display = "none";
  resultBox.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });
}


function resetAssessment() {
  submitted = false;

  form.reset();

  resultBox.hidden = true;

  form.style.display = "";

  hideError();

  submitBtn.disabled = false;
  submitBtn.textContent =
    "Submit Assessment";

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

  updateProgress();
}


async function initialize() {
  renderQuestions();

  document
    .querySelectorAll('input[type="radio"]')
    .forEach((input) => {
      input.addEventListener(
        "change",
        updateProgress
      );
    });

  onAuthStateChanged(
    auth,
    async (user) => {
      if (!user) {
        window.location.href =
          "login.html";

        return;
      }

      currentUser = user;

      try {
        const userRef = doc(
          db,
          "users",
          user.uid
        );

        const snapshot =
          await getDoc(userRef);

        if (snapshot.exists()) {
          progressData =
            snapshot.data().osProgress || {};
        } else {
          progressData = {};
        }

      } catch (error) {
        console.error(error);

        showError(
          "Unable to load your OS progress. The assessment can still be attempted, but your result may not save correctly."
        );
      }
    }
  );
}


